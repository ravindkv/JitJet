#!/usr/bin/env python3
"""sketch_ordering_trap.py: the ordering trap of the V-A weight (PYTHIA meMode 22).

Draws, in the rest frame of the decaying hadron, the charged-lepton energy of D+ -> K0bar e+ nu
and of B0bar -> D*+ l- nubar for flat three-body phase space, for the weight
m E_1 (p_2 . p_rest) with the first product of the table contracted with the mother (the same
weight as me_weight in standalone_hadron_decays.py), and for the swapped pairing; writes the
curves and the means into chapter/tikz/decay_ordering.tex.

    /usr/bin/python3 sketch_ordering_trap.py            # numpy only
    .venv/bin/python sketch_ordering_trap.py --pythia    # also PYTHIA at rest, both orderings
"""
import numpy as np, os, sys
rng=np.random.default_rng(1)
def three_body(M,m,N):
    m1,m2,m3=m; out=[]; tot=0
    while tot<N:
        n=400000
        s12=rng.uniform((m1+m2)**2,(M-m3)**2,n); s23=rng.uniform((m2+m3)**2,(M-m1)**2,n)
        E2=(s12-m1**2+m2**2)/(2*np.sqrt(s12)); E3=(M**2-s12-m3**2)/(2*np.sqrt(s12))
        p2=np.sqrt(np.clip(E2**2-m2**2,0,None)); p3=np.sqrt(np.clip(E3**2-m3**2,0,None))
        ok=(s23>(E2+E3)**2-(p2+p3)**2)&(s23<(E2+E3)**2-(p2-p3)**2)
        s12=s12[ok]; s23=s23[ok]; s13=M**2+m1**2+m2**2+m3**2-s12-s23
        E1=(M**2+m1**2-s23)/(2*M); E2=(M**2+m2**2-s13)/(2*M); E3=M-E1-E2
        out.append(np.stack([E1,E2,E3,(s12-m1**2-m2**2)/2,(s23-m2**2-m3**2)/2,(s13-m1**2-m3**2)/2],1)); tot+=ok.sum()
    return np.concatenate(out)[:N]
def spectra(M,m,N=3_000_000):
    a=three_body(M,m,N); E1,E2,E3,p12,p23,p13=a.T
    res={}
    for tag,w in (('ps',np.ones_like(E1)),('ok',M*E1*p23),('sw',M*E2*p13)):
        keep=rng.random(len(w))<w/w.max(); res[tag]=(E1[keep],E2[keep])
    return res
def curve(E,xmax,nb,xs,ys):
    h,edges=np.histogram(E,bins=nb,range=(0,xmax),density=True); c=0.5*(edges[1:]+edges[:-1])
    pts=[(0.0,0.0)]+list(zip(c,h))+[(xmax,0.0)]
    return ' '.join(f"({x*xs:.3f},{y*ys:.3f})" for x,y in pts)
# D+ -> e+ nu K0bar: table order (lepton, neutrino, hadron); B0bar -> nubar l- D*+: (neutrino, lepton, hadron)
D=spectra(1.86966,(0.000511,0.0,0.497611)); B=spectra(5.2796,(0.0,0.000511,2.01026))
mD={t:(D[t][0].mean(),D[t][1].mean()) for t in D}; mB={t:(B[t][1].mean(),B[t][0].mean()) for t in B}   # (lepton, neutrino)
print("D+ (lepton, neutrino):",{t:tuple(round(v,3) for v in mD[t]) for t in mD}); print("B0bar (lepton, neutrino):",{t:tuple(round(v,3) for v in mB[t]) for t in mB})
xD,yD=6.0,1.35; xB,yB=2.3,3.5
cD={t:curve(D[t][0],0.869,24,xD,yD) for t in D}; cB={t:curve(B[t][1],2.257,24,xB,yB) for t in B}
tex=r"""% ---------------------------------------------------------------------------
% The ordering trap of the V-A weight (meMode 22). (a) The rule: the decaying
% fermion is contracted with the antifermion of the lepton pair, as in muon
% decay; that is the antineutrino for b -> c l- nubar and the charged lepton
% for c -> s l+ nu, and the table lists that product first. The mother's
% partner is the soft one. (b) The lepton energy in D+ -> K0bar e+ nu at rest
% for flat phase space, the table's pairing (soft lepton) and the swapped
% pairing (hard lepton). (c) The same for B0bar -> D*+ l- nubar, where the
% roles are exchanged. The curves are three million flat phase-space draws
% weighted with m E_1 (p_2 . p_3), the weight of me_weight in the script; the
% means in brackets are PYTHIA at rest, fed the channel in the table's order
% and with the two leptons swapped.
% Generated by example/Decay/Standalone/sketch_ordering_trap.py (--pythia adds the PYTHIA check).
% ---------------------------------------------------------------------------
\begin{tikzpicture}[x=1cm,y=1cm,
  every node/.style={font=\footnotesize},
  lab/.style={font=\scriptsize,align=center},
  head/.style={font=\small\bfseries},
  ferm/.style={thick,postaction={decorate},decoration={markings,mark=at position 0.55 with {\arrow{Stealth}}}},
  soft/.style={draw=blue!70!black,thick,rounded corners=2pt,inner sep=1.5pt,text=blue!70!black},
  wav/.style={decorate,decoration={snake,amplitude=0.6mm,segment length=2.2mm},thick,blue!70!black}]
% ---------------- (a) the rule ----------------------------------------------------------------------
\begin{scope}
\node[head,anchor=west] at (-0.3,4.4) {(a) who pairs with the mother: the antifermion of the lepton pair, and it is the soft one};
\foreach \y/\mo/\da/\lep/\anu/\tab/\colr in {
   3.3/{$\mu^-$}/{$\nu_\mu$}/{$e^-$}/{$\bar\nu_e$}/{muon decay: $|\mathcal M|^2\propto(p_\mu\!\cdot p_{\bar\nu_e})(p_{\nu_\mu}\!\cdot p_e)$, the $\bar\nu_e$ spectrum $x^2(1-x)$, the electron's $x^2(3-2x)$}/black,
   1.9/{$b$}/{$c$}/{$\ell^-$}/{$\bar\nu_\ell$}/{$b\to c\ell^-\bar\nu$: $|\mathcal M|^2\propto(p_b\!\cdot p_{\bar\nu})(p_c\!\cdot p_\ell)$; $B$ table \texttt{12 -11 -413}, the neutrino first: the lepton is hard}/red!75!black,
   0.5/{$c$}/{$s$}/{$\nu_\ell$}/{$\ell^+$}/{$c\to s\ell^+\nu$: $|\mathcal M|^2\propto(p_c\!\cdot p_{\ell^+})(p_s\!\cdot p_\nu)$; $D$ table \texttt{-11 12 311}, the lepton first: the lepton is soft}/orange!80!black} {
  \draw[ferm,\colr] (0,\y) -- (1.5,\y) node[midway,above,soft] {\mo};
  \draw[ferm,\colr] (1.5,\y) -- (3.2,\y) node[midway,above,lab] {\da};
  \draw[wav] (1.5,\y) -- (2.3,{\y-0.55});
  \draw[ferm,green!50!black] (2.3,{\y-0.55}) -- (3.4,{\y-0.25}) node[right,lab] {\lep};
  \draw[ferm,green!50!black] (2.3,{\y-0.55}) -- (3.4,{\y-0.85}) node[right,soft] {\anu};
  \node[lab,anchor=west,align=left,text width=10.6cm] at (4.4,{\y-0.35}) {\tab};
}
\node[lab,anchor=north west,text width=15.2cm,align=left,text=black!65] at (-0.3,-0.8) {framed: the two four-vectors contracted in the first factor, $(p_{\mathrm{mother}}\cdot p_1)$ with $p_1$ the first product of the channel; the weight is $M\,E_1\,(p_2\cdot p_3)$ in the rest frame. The factor $(p_2\cdot p_3)$ wants a large mass of the other two, which starves the first, and $E_1$ does not make up for it. A port that pairs the mother with the neutrino in every table gets the $B$ right and every charm decay backwards};
\end{scope}
% ---------------- (b) D+ at rest ---------------------------------------------------------------------
\begin{scope}[yshift=-7.1cm]
\node[head,anchor=west] at (-0.3,4.4) {(b) $D^+\to\bar K^0e^+\nu_e$ at rest: the lepton is soft};
\draw[-{Stealth}] (0,0) -- (6.2,0) node[anchor=north west,lab,xshift=-0.9cm,yshift=-0.08cm] {$E_{e^+}$ [GeV]};
\draw[-{Stealth}] (0,0) -- (0,3.6) node[above,lab] {$\mathrm{d}N/\mathrm{d}E$};
\foreach \x in {0.2,0.4,0.6,0.8} {\draw ({\x*6},-0.06) -- ({\x*6},0.06); \node[lab,anchor=north] at ({\x*6},-0.08) {\x};}
\fill[black!12] plot[smooth] coordinates {PSD} -- cycle;
\draw[black!50,thick] plot[smooth] coordinates {PSD};
\draw[red!75!black,very thick,densely dashed] plot[smooth] coordinates {SWD};
\draw[orange!80!black,very thick] plot[smooth] coordinates {OKD};
\draw[black!60,dashed] (5.214,0) -- (5.214,3.3); \node[lab,anchor=south east] at (5.4,3.35) {end point $\frac{m_D^2-m_K^2}{2m_D}=0.87$};
\node[lab,anchor=north west,align=left] at (-0.3,-0.55) {\textcolor{black!60}{phase space: $\langle E\rangle=MPSD\GeV$}\\[1pt]
\textcolor{orange!80!black}{table order, lepton first: $MOKD$ (\PYTHIA $0.499$)}\\[1pt]
\textcolor{red!75!black}{swapped, neutrino first: $MSWD$ (\PYTHIA $0.567$)}};
\end{scope}
% ---------------- (c) B0bar at rest --------------------------------------------------------------------
\begin{scope}[xshift=8.6cm,yshift=-7.1cm]
\node[head,anchor=west] at (-0.3,4.4) {(c) $\bar B^0\to D^{*+}\ell^-\bar\nu_\ell$ at rest: the lepton is hard};
\draw[-{Stealth}] (0,0) -- (6.2,0) node[anchor=north west,lab,xshift=-0.9cm,yshift=-0.08cm] {$E_\ell$ [GeV]};
\draw[-{Stealth}] (0,0) -- (0,3.6) node[above,lab] {$\mathrm{d}N/\mathrm{d}E$};
\foreach \x in {0.5,1.0,1.5,2.0} {\draw ({\x*2.3},-0.06) -- ({\x*2.3},0.06); \node[lab,anchor=north] at ({\x*2.3},-0.08) {\x};}
\fill[black!12] plot[smooth] coordinates {PSB} -- cycle;
\draw[black!50,thick] plot[smooth] coordinates {PSB};
\draw[red!75!black,very thick,densely dashed] plot[smooth] coordinates {SWB};
\draw[orange!80!black,very thick] plot[smooth] coordinates {OKB};
\draw[black!60,dashed] (5.191,0) -- (5.191,3.3); \node[lab,anchor=south east] at (5.4,3.35) {end point $\frac{m_B^2-m_{D^*}^2}{2m_B}=2.26$};
\node[lab,anchor=north west,align=left] at (-0.3,-0.55) {\textcolor{black!60}{phase space: $\langle E\rangle=MPSB\GeV$}\\[1pt]
\textcolor{orange!80!black}{table order, neutrino first: $MOKB$ (\PYTHIA $1.404$)}\\[1pt]
\textcolor{red!75!black}{swapped, lepton first: $MSWB$ (\PYTHIA $1.265$)}};
\end{scope}
\end{tikzpicture}
"""
for k,v in (('MPSD',f"{mD['ps'][0]:.2f}"),('MOKD',f"{mD['ok'][0]:.2f}"),('MSWD',f"{mD['sw'][0]:.2f}"),
            ('MPSB',f"{mB['ps'][0]:.2f}"),('MOKB',f"{mB['ok'][0]:.2f}"),('MSWB',f"{mB['sw'][0]:.2f}"),
            ('PSD',cD['ps']),('OKD',cD['ok']),('SWD',cD['sw']),('PSB',cB['ps']),('OKB',cB['ok']),('SWB',cB['sw'])):
    assert tex.count(k)>=1, k
    tex=tex.replace(k,v)
out=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..','..','chapter','tikz','decay_ordering.tex')
open(out,'w').write(tex); print("wrote",os.path.normpath(out))

if '--pythia' in sys.argv:
    # the same two channels in PYTHIA at rest, in the table's order and with the two leptons swapped
    import pythia8mc as pythia8
    def run(pid, prods, label, n=20000):
        p=pythia8.Pythia("",False)
        for s in ("ProcessLevel:all = off","Next:numberCount = 0","Print:quiet = on","HadronLevel:Decay = on","ParticleDecays:limitTau0 = off"):
            p.readString(s)
        p.readString(f"{pid}:onMode = off"); p.readString(f"{pid}:addChannel = 1 0.1 22 "+" ".join(str(x) for x in prods))
        for q in prods: p.readString(f"{abs(q)}:mayDecay = off")
        p.init(); m=p.particleData.m0(pid); El=[]; En=[]
        for i in range(n):
            p.event.reset(); p.event.append(pid,1,0,0,0.,0.,0.,m,m)
            if not p.next(): continue
            for k in range(2,p.event.size()):
                d=p.event[k]
                if d.mother1()!=1: continue
                if abs(d.id()) in (11,13): El.append(d.e())
                if abs(d.id()) in (12,14): En.append(d.e())
        print(f"PYTHIA {label}: <E_l>={np.mean(El):.3f} <E_nu>={np.mean(En):.3f} GeV ({len(El)} decays)")
    run(411,[-11,12,311],"D+ -> e+ nu K0bar, table order (lepton first)")
    run(411,[12,-11,311],"D+ -> nu e+ K0bar, swapped (neutrino first)")
    run(511,[12,-11,-413],"B0 -> nu e+ D*-, table order (neutrino first)")
    run(511,[-11,12,-413],"B0 -> e+ nu D*-, swapped (lepton first)")
